def normalize_answer(answer: str) -> str:
    """
    Normalizes model output like 'Yes', '**Yes**', ' yes ', etc.
    """
    if not isinstance(answer, str):
        return ""
    cleaned = answer.strip().lower().replace("*", "")
    return cleaned



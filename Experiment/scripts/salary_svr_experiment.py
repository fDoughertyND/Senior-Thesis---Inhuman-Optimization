def text_color(val, vmin, vmax):
    if pd.isna(val):
        return "white"
    norm = (val - vmin) / (vmax - vmin + 1e-9)

    if 0.25 <= norm <= 0.75:
        return "black"   # middle 50%
    else:
        return "white"   # extremes

